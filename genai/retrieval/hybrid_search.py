# ADAPTIVE HYBRID SEARCH
# ==================================================

class HybridSearch:

    def __init__(self):

        print("Initializing BM25 search...")
        self.bm25 = BM25Search()

        print("Initializing query analyzer...")
        self.query_analyzer = QueryAnalyzer()

        print("Initializing query expander...")
        self.query_expander = QueryExpander()

        print("Initializing cross-encoder reranker...")
        self.reranker = CrossEncoderReranker()

        print("Adaptive hybrid retrieval initialized.")

    # --------------------------------------------------
    # RETRIEVE ONE QUERY
    # --------------------------------------------------

    def _retrieve_one_query(
        self,
        query: str,
        candidate_count: int,
        source_prefix: str = "",
    ) -> List[Tuple[str, list]]:
        """
        Execute dense and BM25 retrieval for one query.

        Standard retrieval preserves the source names:
            dense
            bm25

        Other strategies use unique source names.
        """

        dense_results = semantic_search(
            query=query,
            top_k=candidate_count,
        )

        bm25_results = self.bm25.search(
            query=query,
            top_k=candidate_count,
        )

        if source_prefix:

            dense_source = f"{source_prefix}_dense"
            bm25_source = f"{source_prefix}_bm25"

        else:

            dense_source = "dense"
            bm25_source = "bm25"

        return [
            (dense_source, dense_results),
            (bm25_source, bm25_results),
        ]

    # --------------------------------------------------
    # MAIN SEARCH
    # --------------------------------------------------

    def search(
        self,
        query: str,
        top_k: int = DEFAULT_TOP_K,
        strategy: str = None,
    ) -> List[Dict]:

        if not isinstance(query, str) or not query.strip():
            raise ValueError("Query cannot be empty.")

        if (
            not isinstance(top_k, int)
            or isinstance(top_k, bool)
            or not 1 <= top_k <= 100
        ):
            raise ValueError(
                "top_k must be between 1 and 100."
            )

        if strategy is not None and not isinstance(strategy, str):
            raise ValueError("strategy must be a string or None.")

        start_time = time.perf_counter()

        # 1. Analyze the original query.
        analysis = self.query_analyzer.analyze(query)

        # 2. Select retrieval strategy.
        selected_strategy = (
            strategy.strip().upper()
            if strategy and strategy.strip()
            else analysis["strategy"]
        )

        allowed_strategies = {
            "STANDARD",
            "KEYWORD_FOCUSED",
            "EXPANDED",
        }

        if selected_strategy not in allowed_strategies:

            raise ValueError(
                f"Unsupported strategy: {selected_strategy}"
            )

        print("\n========== ADAPTIVE RETRIEVAL ==========")
        print("Original query:", query)
        print("Selected strategy:", selected_strategy)

        ranked_lists = []
        variants = []

        # --------------------------------------------------
        # STRATEGY 1: STANDARD
        # --------------------------------------------------

        if selected_strategy == "STANDARD":

            ranked_lists.extend(
                self._retrieve_one_query(
                    query=query,
                    candidate_count=CANDIDATE_COUNT,
                )
            )

        # --------------------------------------------------
        # STRATEGY 2: KEYWORD-FOCUSED
        # --------------------------------------------------

        elif selected_strategy == "KEYWORD_FOCUSED":

            ranked_lists.extend(
                self._retrieve_one_query(
                    query=query,
                    candidate_count=KEYWORD_CANDIDATE_COUNT,
                    source_prefix="keyword",
                )
            )

        # --------------------------------------------------
        # STRATEGY 3: EXPANDED
        # --------------------------------------------------

        elif selected_strategy == "EXPANDED":

            variants = self.query_expander.expand(query)

            all_queries = [query] + variants

            print(
                "Generated query variants:",
                len(variants),
            )

            for index, search_query in enumerate(all_queries):

                if index == 0:
                    prefix = "original"
                else:
                    prefix = f"expanded_{index}"

                ranked_lists.extend(
                    self._retrieve_one_query(
                        query=search_query,
                        candidate_count=CANDIDATE_COUNT,
                        source_prefix=prefix,
                    )
                )

        # --------------------------------------------------
        # RECIPROCAL RANK FUSION
        # --------------------------------------------------

        # Each retrieval source contributes at most
        # candidate_count unique candidates.
        #
        # Therefore this is a safe upper bound for the
        # number of unique candidates before fusion.

        fusion_candidate_limit = (
            CANDIDATE_COUNT * len(ranked_lists)
            if selected_strategy == "EXPANDED"
            else (
                KEYWORD_CANDIDATE_COUNT * len(ranked_lists) // 2
                if selected_strategy == "KEYWORD_FOCUSED"
                else CANDIDATE_COUNT
            )
        )

        fused_results = reciprocal_rank_fusion(
            ranked_lists=ranked_lists,
            top_k=max(1, fusion_candidate_limit),
            rrf_k=RRF_K,
        )

        print("Retrieval sources:", len(ranked_lists))
        print("Fused candidates:", len(fused_results))

        # --------------------------------------------------
        # CROSS-ENCODER RERANKING
        # --------------------------------------------------

        reranked_results = self.reranker.rerank(
            query=query,
            documents=fused_results,
            top_k=top_k,
        )

        elapsed_ms = (
            time.perf_counter() - start_time
        ) * 1000

        # --------------------------------------------------
        # TRACE METADATA
        # --------------------------------------------------

        for result in reranked_results:

            result["retrieval_strategy"] = selected_strategy

            result["query_variants"] = variants.copy()

            result["retrieval_latency_ms"] = round(
                elapsed_ms,
                2,
            )

            result["retrieval_source_count"] = len(
                ranked_lists
            )

            result["fusion_candidate_count"] = len(
                fused_results
            )

        print("Final results:", len(reranked_results))

        print(
            "Retrieval latency:",
            round(elapsed_ms, 2),
            "ms",
        )

        return reranked_results


# ==================================================
# INTERACTIVE TESTING
# ==================================================

def main():

    search_engine = HybridSearch()

    query = input(
        "\nEnter your question: "
    ).strip()

    if not query:

        print("Please enter a valid question.")
        return

    results = search_engine.search(
        query=query,
        top_k=DEFAULT_TOP_K,
    )

    print(
        "\n========== ADAPTIVE HYBRID RESULTS =========="
    )

    for rank, result in enumerate(results, start=1):

        print(f"\nRank: {rank}")

        print("Chunk:", result["chunk_id"])
        print("Document:", result["document_id"])
        print("Source:", result["source_file"])
        print("Page:", result["page_number"])

        print("Dense Rank:", result.get("dense_rank"))
        print("BM25 Rank:", result.get("bm25_rank"))

        print(
            "RRF Score:",
            round(result["rrf_score"], 6),
        )

        print(
            "Rerank Score:",
            round(result["rerank_score"], 4),
        )

        print(
            "Strategy:",
            result["retrieval_strategy"],
        )

        print(
            "Retrieval Sources:",
            result["retrieval_source_count"],
        )

        print(
            "Fusion Candidates:",
            result["fusion_candidate_count"],
        )

        print("Content:", result["text"][:600])

        print("-" * 70)


if __name__ == "__main__":
    main()
