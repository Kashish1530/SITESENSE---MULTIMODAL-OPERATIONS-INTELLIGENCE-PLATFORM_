
from collections import defaultdict
from typing import Dict, List, Tuple
import re
import time

from genai.retrieval.bm25_search import BM25Search
from genai.retrieval.pgvector_search import semantic_search
from genai.retrieval.reranker import CrossEncoderReranker
from genai.retrieval.query_analyzer import QueryAnalyzer


# ==================================================
# CONFIGURATION
# ==================================================

RRF_K = 60

CANDIDATE_COUNT = 20
KEYWORD_CANDIDATE_COUNT = 40

DEFAULT_TOP_K = 5
EXPANDED_MAX_VARIANTS = 3


# ==================================================
# QUERY EXPANSION
# ==================================================

class QueryExpander:
    """
    Deterministic query expansion using domain terminology.

    Generates additional search formulations without
    requiring an external LLM or API.
    """

    EXPANSION_TERMS = {

        "incidents": [
            "workplace accident reporting procedure",
            "incident investigation and corrective actions",
        ],

        "near misses": [
            "workplace incident reporting",
            "hazard notification and investigation procedure",
        ],

        "forklift": [
            "powered industrial truck operator safety",
            "forklift operating procedures and precautions",
        ],

        "ppe": [
            "personal protective equipment requirements",
            "protective equipment selection inspection maintenance",
        ],

        "incident": [
            "workplace accident reporting procedure",
            "near miss notification and investigation",
        ],

        "near miss": [
            "workplace incident reporting",
            "hazard and accident investigation procedure",
        ],

        "chemical": [
            "hazardous substance handling and storage",
            "chemical safety precautions and spill response",
        ],

        "chemicals": [
            "hazardous substance handling and storage",
            "chemical safety precautions and spill response",
        ],

        "handling chemicals": [
            "chemical handling procedures and precautions",
            "hazardous substance storage and spill response",
        ],

        "electrical": [
            "electrical hazard control and equipment inspection",
            "electrical isolation and lockout procedures",
        ],

        "manual handling": [
            "safe lifting and carrying procedures",
            "moving heavy materials ergonomic precautions",
        ],

        "pedestrian": [
            "pedestrian walkway segregation",
            "vehicle and pedestrian traffic management",
        ],

        "evacuation": [
            "emergency evacuation procedure",
            "emergency exits assembly points and alarms",
        ],
    }

    def expand(
        self,
        query: str,
        max_variants: int = EXPANDED_MAX_VARIANTS,
    ) -> List[str]:

        if not isinstance(query, str) or not query.strip():
            raise ValueError("Query cannot be empty.")

        if (
            not isinstance(max_variants, int)
            or isinstance(max_variants, bool)
            or max_variants < 1
        ):
            raise ValueError(
                "max_variants must be a positive integer."
            )

        normalized = query.lower().strip()

        variants = []
        seen = {normalized}

        for keyword, expansions in self.EXPANSION_TERMS.items():

            pattern = rf"\b{re.escape(keyword)}\b"

            if re.search(pattern, normalized):

                for expansion in expansions:

                    candidate = f"{query} {expansion}"
                    candidate_key = candidate.lower()

                    if candidate_key not in seen:

                        variants.append(candidate)
                        seen.add(candidate_key)

                    if len(variants) >= max_variants:
                        return variants

        return variants


# ==================================================
# RECIPROCAL RANK FUSION
# ==================================================

def reciprocal_rank_fusion(
    ranked_lists,
    top_k: int = DEFAULT_TOP_K,
    rrf_k: int = RRF_K,
) -> List[Dict]:
    """
    Combine multiple ranked lists using Reciprocal Rank Fusion.

    Supports large candidate pools generated by expanded
    queries.

    Each retrieval source must have a unique name.

    Example:
        ("dense", dense_results)
        ("bm25", bm25_results)
        ("original_dense", original_dense_results)
        ("expanded_1_bm25", expanded_bm25_results)
    """

    if (
        not isinstance(top_k, int)
        or isinstance(top_k, bool)
        or top_k < 1
    ):
        raise ValueError(
            "top_k must be a positive integer."
        )

    if (
        not isinstance(rrf_k, int)
        or isinstance(rrf_k, bool)
        or rrf_k < 1
    ):
        raise ValueError(
            "rrf_k must be a positive integer."
        )

    scores = defaultdict(float)
    documents = {}
    source_ranks = defaultdict(dict)

    for source_name, ranked_list in ranked_lists:

        for rank, result in enumerate(ranked_list, start=1):

            chunk_id = result["chunk_id"]

            scores[chunk_id] += 1.0 / (rrf_k + rank)

            source_ranks[chunk_id][source_name] = rank

            if chunk_id not in documents:
                documents[chunk_id] = result.copy()

    ranked_chunks = sorted(
        scores.items(),
        key=lambda item: item[1],
        reverse=True,
    )

    fused_results = []

    for chunk_id, score in ranked_chunks[:top_k]:

        result = documents[chunk_id].copy()

        result["rrf_score"] = score

        result["source_ranks"] = (
            source_ranks[chunk_id].copy()
        )

        # Backward compatibility with standard hybrid search.
        result["dense_rank"] = (
            source_ranks[chunk_id].get("dense")
        )

        result["bm25_rank"] = (
            source_ranks[chunk_id].get("bm25")
        )

        fused_results.append(result)

    return fused_results


